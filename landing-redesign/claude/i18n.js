  function applyLang(lang) {
    var dict = window.PF_I18N[lang] || window.PF_I18N.en;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] != null) el.textContent = dict[key];
    });
    try { localStorage.setItem("pf_lang", lang); } catch (e) {}
  }

  function currentLang() {
    try { return localStorage.getItem("pf_lang") || "en"; } catch (e) { return "en"; }
  }

  window.PF_setLang = applyLang;
  window.PF_currentLang = currentLang;

  document.addEventListener("DOMContentLoaded", function () {
    applyLang(currentLang());
    var toggle = document.getElementById("lang-toggle");
    if (toggle) {
      toggle.addEventListener("click", function () {
        applyLang(currentLang() === "en" ? "ar" : "en");
      });
    }
  });
