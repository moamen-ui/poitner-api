#!/usr/bin/env node
// Verifies the Layer-B harness fixes WITHOUT any paid AI tool (`claude -p`/`opencode run`) —
// see docs/E2E_TEST_PLAN.md "Layer B tests the branch under test" for the bugs this exists to
// prove fixed. Stands up its OWN isolated docker-compose project (alternate ports, its own
// project name — never touches the shared dev stack on :8090/:5433/:4873, nor a concurrently
// running `scripts/local-e2e-gate.sh` stack on :8091/:5434/:4874), resets+seeds it, builds the
// scratch TC6 repo exactly as `harness.mjs`'s `runCase()` would, then runs the CLI itself
// (`npx ... pointer-feedback ...`) directly — no AI tool in the loop — and tears the stack down
// unconditionally afterward, pass or fail.
//
// Usage: node e2e/ai/dry-run-verify.mjs
import { execFileSync, execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { existsSync, mkdirSync, rmSync, writeFileSync, readFileSync, copyFileSync, cpSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const execFileP = promisify(execFile);
const here = dirname(fileURLToPath(import.meta.url));
const E2E_ROOT = join(here, '..');
const REPO_ROOT = join(E2E_ROOT, '..');
const STATE_DIR = join(E2E_ROOT, 'state');

// Deliberately far from every other port this repo's docs assign (dev stack 8090/5433/8025/1025/
// 4873; scripts/local-e2e-gate.sh's isolated stack 8091/5434/8026/1026/4874) — see
// e2e/scripts/lib/constants.mjs's PORTS for the full registry of what NOT to collide with.
const PROJECT = 'pointer-e2e-ai-dryrun';
const API_PORT = 8098;
const DB_PORT = 5438;
const VERDACCIO_PORT = 4878;
const MAILPIT_HTTP_PORT = 8098 + 1000; // 9098 — mailpit isn't asked for on the `up -d` command
const MAILPIT_SMTP_PORT = 1098; // below, but api depends_on it, so compose starts it anyway with
// whatever ports THIS override gives it — left unoverridden, it re-publishes the base file's
// 8025/1025, which collides with any other stack (dev, gate, another dry run) already using them.

const OVERRIDE_FILE = join(STATE_DIR, 'dryrun-compose-override.yaml');
const BASE_COMPOSE_FILE = join(REPO_ROOT, 'docker-compose.yaml');

const API_URL = `http://localhost:${API_PORT}`;
const VERDACCIO_URL = `http://localhost:${VERDACCIO_PORT}`;

function log(msg) {
  console.log(`==> ${msg}`);
}

function dc(args, opts = {}) {
  return execFileSync(
    'docker',
    ['compose', '-p', PROJECT, '-f', BASE_COMPOSE_FILE, '-f', OVERRIDE_FILE, ...args],
    {
      cwd: REPO_ROOT,
      stdio: 'inherit',
      // `verdaccio` is `profiles: [e2e-nightly]` in docker-compose.yaml (it's opt-in for the shared
      // dev stack). Naming it explicitly on `up -d` starts it regardless of active profiles, but a
      // bare `down` (no service args — compose has no service-scoped `down`) only tears down
      // services whose profile is currently active; without this, `down` silently left the
      // verdaccio container (and its volume) running after every single teardown below —
      // confirmed directly: `docker ps` after a full run+teardown still showed it Up.
      env: { ...process.env, COMPOSE_PROFILES: 'e2e-nightly' },
      ...opts,
    },
  );
}

async function waitFor(url, timeoutMs, label) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    try {
      const res = await fetch(url);
      if (res.ok) return;
    } catch {
      // not up yet
    }
    await new Promise((r) => setTimeout(r, 1500));
  }
  throw new Error(`${label} did not become ready at ${url} within ${timeoutMs}ms`);
}

function runNpx(args, cwd, env) {
  return new Promise((resolvePromise) => {
    execFile('npx', args, { cwd, env: { ...process.env, ...env }, maxBuffer: 16 * 1024 * 1024 }, (err, stdout, stderr) => {
      resolvePromise({ code: err ? (err.code ?? 1) : 0, stdout, stderr });
    });
  });
}

async function main() {
  mkdirSync(STATE_DIR, { recursive: true });

  // Mirrors scripts/local-e2e-gate.sh: a real developer checkout has .env, but this dry run may be
  // the first thing ever run against this worktree.
  const envPath = join(REPO_ROOT, '.env');
  if (!existsSync(envPath)) {
    log('.env missing — copying .env.example (same as scripts/local-e2e-gate.sh does)');
    copyFileSync(join(REPO_ROOT, '.env.example'), envPath);
  }

  log(`Writing isolated compose override (project ${PROJECT}, api :${API_PORT}, db :${DB_PORT}, verdaccio :${VERDACCIO_PORT})`);
  writeFileSync(
    OVERRIDE_FILE,
    [
      '# Generated by e2e/ai/dry-run-verify.mjs — do not hand-edit, do not commit.',
      'services:',
      '  db:',
      '    ports: !override',
      `      - "${DB_PORT}:5432"`,
      '  api:',
      '    ports: !override',
      `      - "${API_PORT}:8080"`,
      '  verdaccio:',
      '    ports: !override',
      `      - "${VERDACCIO_PORT}:4873"`,
      '  mailpit:',
      '    ports: !override',
      `      - "${MAILPIT_HTTP_PORT}:8025"`,
      `      - "${MAILPIT_SMTP_PORT}:1025"`,
      '',
    ].join('\n'),
    'utf8',
  );

  let failed = null;
  try {
    log('Tearing down any stale project with this name (best-effort)');
    try {
      dc(['down', '-v', '--remove-orphans']);
    } catch {
      // fine — nothing to tear down yet
    }

    log('Starting db + api + verdaccio (fresh volumes)');
    dc(['up', '-d', 'db', 'api', 'verdaccio']);

    log(`Waiting for API at ${API_URL} ...`);
    await waitFor(`${API_URL}/swagger/v1/swagger.json`, 180_000, 'API');
    log(`Waiting for Verdaccio at ${VERDACCIO_URL} ...`);
    await waitFor(`${VERDACCIO_URL}/-/ping`, 60_000, 'Verdaccio');

    log('Seeding deterministic e2e fixtures (reset.sh already gave us a fresh DB, so seed.mjs alone is enough)');
    execFileSync('node', ['scripts/seed.mjs'], {
      cwd: E2E_ROOT,
      env: { ...process.env, E2E_API_URL: API_URL },
      stdio: 'inherit',
    });

    // Everything below reads process.env at IMPORT time (e2e/scripts/lib/api.mjs's BASE_URL,
    // registry.mjs's REGISTRY_URL, …) — set before the first dynamic import of any of them so
    // those modules pick up this isolated stack rather than the shared dev one.
    process.env.E2E_API_URL = API_URL;
    process.env.VERDACCIO_URL = VERDACCIO_URL;
    const dryRunPointerConfig = join(STATE_DIR, 'dryrun-pointer-config');
    rmSync(dryRunPointerConfig, { recursive: true, force: true });
    mkdirSync(dryRunPointerConfig, { recursive: true });

    const { publishLocalCli, installSkills, installRepoState, installNpmRegistry, npmRegistryEnv, SUB_SKILLS } =
      await import('./harness.mjs');
    const { raw, login } = await import('../scripts/lib/api.mjs');
    const { USERS, PROJECTS } = await import('../scripts/lib/constants.mjs');
    const { REGISTRY_URL } = await import('../scripts/lib/registry.mjs');

    log(`Publishing the local cli/ build to this stack's Verdaccio (${REGISTRY_URL}) ...`);
    const cliVersion = await publishLocalCli();
    log(`Published pointer-feedback@${cliVersion}`);

    // Build the scratch repo exactly as harness.mjs's runCase() would for TC6, minus the AI
    // invocation itself.
    const scratchDir = join(STATE_DIR, 'dryrun-scratch-tc6');
    rmSync(scratchDir, { recursive: true, force: true });
    mkdirSync(scratchDir, { recursive: true });
    cpSync(join(E2E_ROOT, 'fixture-app', 'tc6'), scratchDir, { recursive: true });

    log('Installing skills (all four served files) + npm registry override + real .pointer config...');
    await installSkills(scratchDir, '.claude/skills');
    installNpmRegistry(scratchDir);
    await installRepoState(scratchDir, PROJECTS.tc6.key, 'claude-code', cliVersion);

    const checks = [];

    // Check A — all four skill files present (issue 3).
    const skillFiles = [
      '.claude/skills/pointer-init/SKILL.md',
      '.claude/skills/pointer-feedback/SKILL.md',
      ...SUB_SKILLS.map((n) => `.claude/skills/pointer-feedback/${n}.md`),
    ];
    const missingSkillFiles = skillFiles.filter((f) => !existsSync(join(scratchDir, f)));
    checks.push({
      name: 'all 4 skill files installed',
      pass: missingSkillFiles.length === 0,
      detail: missingSkillFiles.length ? `missing: ${missingSkillFiles.join(', ')}` : skillFiles.join(', '),
    });

    // Check B — .pointer/config.json + credentials.env present (issue 4).
    const configPresent = existsSync(join(scratchDir, '.pointer', 'config.json'));
    const credsPresent = existsSync(join(scratchDir, '.pointer', 'credentials.env'));
    checks.push({
      name: '.pointer/config.json + credentials.env written (real pointer init shape)',
      pass: configPresent && credsPresent,
      detail: JSON.stringify({ configPresent, credsPresent }),
    });

    // Check C — npx resolves the LOCAL build, not the published npmjs package (issue 2). The
    // `npm_config_registry` env var, not the scratch `.npmrc`, is what actually does this — see
    // harness.mjs's `npmRegistryEnv` for why the .npmrc alone is not reliable here.
    const npxEnv = { POINTER_CONFIG_DIR: dryRunPointerConfig, ...npmRegistryEnv() };
    const versionRes = await runNpx(['-y', 'pointer-feedback@latest', '--version'], scratchDir, npxEnv);
    const resolvedVersion = versionRes.stdout.trim();
    checks.push({
      name: 'npx -y pointer-feedback@latest --version resolves the LOCAL build',
      pass: versionRes.code === 0 && resolvedVersion === cliVersion,
      detail: `expected ${cliVersion}, got code=${versionRes.code} stdout="${resolvedVersion}" stderr="${versionRes.stderr.trim()}"`,
    });

    // Check D — the min-CLI-version gate is at its normal default, not stuck raised (issue 1).
    const metaRes = await raw('GET', '/api/meta');
    checks.push({
      name: 'server minCliVersion is the configured default (0.1.0), not a stuck 99.0.0',
      pass: metaRes.data?.minCliVersion === '0.1.0',
      detail: `minCliVersion=${metaRes.data?.minCliVersion}`,
    });

    // Check E — `apply --plan` succeeds and shows the branch's rewritten precedence text
    // (cli/src/apply/prompt.ts's AI_RULES_PRECEDENCE_TEXT), against a real seeded TC6 comment.
    const planRes = await runNpx(['-y', 'pointer-feedback', 'apply', '--plan'], scratchDir, npxEnv);
    const marker = 'MANDATORY: AI RULES PRECEDENCE & HIERARCHY';
    checks.push({
      name: 'npx pointer-feedback apply --plan succeeds and prints the branch precedence text',
      pass: planRes.code === 0 && planRes.stdout.includes(marker),
      detail: `code=${planRes.code}, containsMarker=${planRes.stdout.includes(marker)}, stderr="${planRes.stderr.trim().slice(0, 500)}"`,
    });

    // Check F — the seeded TC6 comment actually carries BOTH ai rules (project + personal), i.e.
    // the server-side data this whole scenario needs is really there.
    const expected = JSON.parse(readFileSync(join(STATE_DIR, 'expected.json'), 'utf8'));
    const dev = await login(USERS.developer.email, USERS.developer.password, { forceFresh: true });
    const commentRes = await raw('GET', `/api/comments/${expected.tc6.commentId}`, { token: dev.token });
    const aiRules = commentRes.data?.aiRules || [];
    checks.push({
      name: 'GET /api/comments/<tc6 id> returns both seeded aiRules (project + personal)',
      pass: aiRules.length >= 2,
      detail: `aiRules=${JSON.stringify(aiRules.map((r) => ({ scope: r.scope, title: r.title, isPersonal: r.isPersonal })))}`,
    });

    console.log('\n================================================================================');
    console.log(' DRY-RUN VERIFICATION (no paid AI tool invoked)');
    console.log('================================================================================');
    for (const c of checks) {
      console.log(`[${c.pass ? 'PASS' : 'FAIL'}] ${c.name}`);
      console.log(`       ${c.detail}`);
    }
    console.log('================================================================================');

    if (checks.some((c) => !c.pass)) {
      failed = new Error('one or more dry-run checks failed — see above');
    }
  } finally {
    log(`Tearing down isolated project ${PROJECT}`);
    try {
      dc(['down', '-v', '--remove-orphans']);
    } catch (err) {
      console.error('teardown reported an error — check for leftover containers manually:', err.message);
    }
    try {
      rmSync(OVERRIDE_FILE, { force: true });
    } catch {
      // best-effort
    }
  }

  if (failed) throw failed;
  log('All checks passed.');
}

main().catch((err) => {
  console.error('dry-run-verify FAILED:', err);
  process.exitCode = 1;
});
